test('bundled plugin registers via real SDK WebSocket; rendering, external feedback and Multi-Actions reach simulated TCP mixer', {timeout:7000}, async t => {
  const localData=await mkdtemp(join(tmpdir(),'studiolive-sdk-'));t.after(()=>rm(localData,{recursive:true,force:true}));
  const fixture = await tcpMixer({port:53000}); t.after(()=>fixture.close());
  const server = new WebSocketServer({port:0,host:'127.0.0.1'});
  await new Promise<void>(resolve=>server.once('listening',resolve));
  t.after(()=>{for(const client of server.clients) client.terminate(); server.close();});
  const received:any[]=[]; let host:any;
  server.on('connection',(socket:any)=>{
    host=socket;
    socket.on('message',(bytes:Buffer)=>{
      const message=JSON.parse(bytes.toString()); received.push(message);
      if(message.event==='getGlobalSettings') socket.send(JSON.stringify({event:'didReceiveGlobalSettings',id:message.id,payload:{settings:{ip:'127.0.0.1'}}}));
    });
  });
  const info={application:{version:'7.6.0',platform:process.platform==='darwin'?'mac':'windows',platformVersion:process.platform==='darwin'?'13.0':'10.0.22631',language:'de',font:'Arial'},devices:[{id:'simdeck',name:'Simulated Deck',type:0,size:{columns:5,rows:3}}],plugin:{uuid:'de.local.studiolive-mutes',version:'1.0.0.0'}};
  const child=spawn(process.execPath,['bin/plugin.js','-port',String(server.address().port),'-pluginUUID','de.local.studiolive-mutes','-registerEvent','registerPlugin','-info',JSON.stringify(info)],{cwd:resolve('de.local.studiolive-mutes.sdPlugin'),env:{...process.env,HOME:localData,LOCALAPPDATA:localData},windowsHide:true,stdio:'pipe'});
  let errors=''; child.stderr.on('data',b=>errors+=b.toString());
  t.after(()=>{child.kill();});
  await until(()=>received.some(m=>m.event==='registerPlugin'),2000);
  await until(()=>fixture.writes.some(b=>b.toString('ascii',6,8)==='JM'),2000);
  const send=(event:string,context:string,operation='toggle',multi=false)=>host.send(JSON.stringify({event,action:'de.local.studiolive-mutes.channel',context,device:'simdeck',payload:{controller:'Keypad',settings:{channel:1,mode:operation},state:0,isInMultiAction:multi,...(multi?{}:{coordinates:{column:0,row:0}})}}));
  const image=(context:string,text:string,after=0)=>received.slice(after).some(m=>{
    if(m.event!=='setImage'||m.context!==context) return false;
    const image=String(m.payload.image); const svg=image.startsWith('data:')?Buffer.from(image.split(',')[1],'base64').toString():image;
    return svg.includes(`>${text}<`);
  });
  send('willAppear','a'); send('willAppear','b'); await until(()=>image('a','OPEN')&&image('b','OPEN'));
  send('propertyInspectorDidAppear','a');
  const nameRequest=(context:string,requestId:string)=>host.send(JSON.stringify({event:'sendToPlugin',action:'de.local.studiolive-mutes.channel',context,device:'simdeck',payload:{type:'targetNames',requestId}}));
  nameRequest('a','names-a');
  const nameReplies=()=>received.filter(message=>message.event==='sendToPropertyInspector'&&message.payload?.type==='targetNames');
  await until(()=>nameReplies().some(message=>message.context==='a'&&message.payload.requestId==='names-a'&&message.payload.names.line[0]==='Input 1'));
  assert.equal(nameReplies().at(-1).payload.names.aux.length,16);assert.equal(fixture.controls.length,0);
  for(const socket of fixture.sockets)socket.write(packet('PS',Buffer.from('line/ch1/username\0\0\0Lead voice\0')));
  await until(()=>nameReplies().at(-1)?.payload.names.line[0]==='Lead voice');
  send('propertyInspectorDidDisappear','a');
  const nameCount=nameReplies().length;
  for(const socket of fixture.sockets)socket.write(packet('PS',Buffer.from('line/ch1/username\0\0\0New name\0')));
  await until(()=>image('b','New name'));
  assert.equal(nameReplies().length,nameCount);
  send('propertyInspectorDidAppear','b');nameRequest('b','names-b');
  await until(()=>nameReplies().some(message=>message.context==='b'&&message.payload.requestId==='names-b'&&message.payload.names.line[0]==='New name'));
  send('propertyInspectorDidDisappear','b');
  const background=(context:string,color:string)=>received.some(m=>m.event==='setImage'&&m.context===context&&Buffer.from(String(m.payload.image).split(',')[1],'base64').toString().includes(`fill="${color}"`));
  await until(()=>background('a','#112233'));
  for(const socket of fixture.sockets)socket.write(packet('PC',Buffer.concat([Buffer.from('line/ch1/color\0\0\0'),Buffer.from([255,255,128,255])])));
  await until(()=>background('a','#ffff80')&&background('b','#ffff80'));assert.equal(fixture.controls.length,0);
  send('keyDown','a','on'); await until(()=>fixture.controls.length===1&&image('b','MUTE'));
  fixture.external(1,false); await until(()=>received.filter(m=>m.event==='setImage'&&m.context==='b').length>=3);
  send('willAppear','multi','on',true); send('keyDown','multi','on',true); await until(()=>fixture.controls.length===2);
  send('keyDown','multi','off',true); await until(()=>fixture.controls.length===3);
  assert.deepEqual(fixture.controls.map(b=>b.readFloatLE(b.length-4)),[1,1,0]);
  send('willDisappear','a'); send('willAppear','new-profile'); await until(()=>image('new-profile','OPEN'));
  const actionEvent=(event:string,context:string,settings:any,level=false)=>host.send(JSON.stringify({event,action:`de.local.studiolive-mutes.${level?'level':'channel'}`,context,device:'simdeck',payload:{controller:'Keypad',settings,state:0,isInMultiAction:true}}));
  const lastControls=()=>fixture.controls.map(b=>({path:b.subarray(0,b.indexOf(0)).toString(),value:b.readFloatLE(b.length-4)}));
  const group={target:'group',channel:1,mode:'on'};
  actionEvent('willAppear','group',group); actionEvent('keyDown','group',group);
  await until(()=>fixture.controls.length===4&&image('group','MUTE')); assert.deepEqual(lastControls().at(-1),{path:'mutegroup/mutegroup1',value:1});
  const auxsend={target:'auxsend',channel:1,mix:1,mode:'on'};
  actionEvent('willAppear','auxsend',auxsend); actionEvent('keyDown','auxsend',auxsend);
  await until(()=>fixture.controls.length===5&&image('auxsend','MUTE')); assert.deepEqual(lastControls().at(-1),{path:'line/ch1/assign_aux1',value:0});
  const level={channel:1,operation:'set',db:-6,duration:0};
  actionEvent('willAppear','level',level,true); actionEvent('keyDown','level',level,true);
  await until(()=>fixture.controls.length===6); assert.equal(lastControls().at(-1)!.path,'line/ch1/volume');
  const fade={...level,db:-24,duration:0.2}; actionEvent('keyDown','level',fade,true);
  await until(()=>fixture.controls.length>=8); await until(()=>image('level','≈ -24.0 dB'),1000);
  assert.ok(lastControls().filter(c=>c.path==='line/ch1/volume').length>=4);
  const zero={...level,db:0,duration:0.12};
  actionEvent('didReceiveSettings','level',zero,true);await until(()=>image('level','FADE UP'));
  actionEvent('keyDown','level',zero,true);await until(()=>image('level','≈ 0.0 dB'));
  await until(()=>image('level','FADE --'));
  assert.equal(lastControls().at(-1)!.value,0.74609375);
  const toggleFade={...level,operation:'toggle',duration:0.12};
  actionEvent('didReceiveSettings','level',toggleFade,true);await until(()=>image('level','FADE OUT'));
  actionEvent('keyDown','level',toggleFade,true);await until(()=>image('level','−∞')&&image('level','FADE IN'));
  assert.equal(lastControls().at(-1)!.value,0);
  const beforeReturn=received.length;
  actionEvent('keyDown','level',toggleFade,true);await until(()=>image('level','≈ 0.0 dB',beforeReturn));
  assert.equal(lastControls().at(-1)!.value,0.74609375);
  for(const [kind,channel,path,name] of [['auxinput',1,'return/ch1','Aux In 1'],['auxinput',2,'return/ch2','Aux In 2'],['tape',1,'return/ch3','Tape In'],['talkback',1,'talkback/ch1','Talkback']] as const){
    const settings={target:kind,channel,mode:'toggle'},context=`special-${path}`;
    actionEvent('willAppear',context,settings);await until(()=>image(context,name));
    const before=fixture.controls.length;actionEvent('keyDown',context,settings);await until(()=>fixture.controls.length===before+1);
    assert.equal(lastControls().at(-1)!.path,`${path}/mute`);assert.equal(lastControls().at(-1)!.value,kind==='talkback'?0:1);
    const levelSettings={target:kind,channel,operation:'set',db:0,duration:0};
    actionEvent('willAppear',`${context}-level`,levelSettings,true);actionEvent('keyDown',`${context}-level`,levelSettings,true);
    await until(()=>fixture.controls.length===before+2&&image(`${context}-level`,'≈ 0.0 dB'));
    assert.deepEqual(lastControls().at(-1),{path:`${path}/volume`,value:0.74609375});
  }
  assert.equal(errors,'');
});

test('saved mixer IP survives a fresh plugin process when Stream Deck global settings are empty', {timeout:10000},async t=>{
  const localData=await mkdtemp(join(tmpdir(),'studiolive-restart-'));t.after(()=>rm(localData,{recursive:true,force:true}));
  const fixture=await tcpMixer({port:53000});t.after(()=>fixture.close());
  const server=new WebSocketServer({port:0,host:'127.0.0.1'});await new Promise<void>(resolve=>server.once('listening',resolve));
  t.after(()=>{for(const client of server.clients)client.terminate();server.close();});
  let host:any;const received:any[]=[];
  server.on('connection',(socket:any)=>{host=socket;socket.on('message',(bytes:Buffer)=>{
    const message=JSON.parse(bytes.toString());received.push(message);
    if(message.event==='getGlobalSettings')socket.send(JSON.stringify({event:'didReceiveGlobalSettings',id:message.id,payload:{settings:{}}}));
  });});
  const children:ReturnType<typeof spawn>[]=[];t.after(()=>{for(const child of children)child.kill();});
  const launch=()=>{
    const info={application:{version:'7.6.0',platform:process.platform==='darwin'?'mac':'windows',platformVersion:process.platform==='darwin'?'13.0':'10.0.22631',language:'en'},devices:[{id:'simdeck',name:'Simulator',type:0,size:{columns:5,rows:3}}],plugin:{uuid:'de.local.studiolive-mutes',version:'1.0.0.0'}};
    const child=spawn(process.execPath,['bin/plugin.js','-port',String(server.address().port),'-pluginUUID','de.local.studiolive-mutes','-registerEvent','registerPlugin','-info',JSON.stringify(info)],{cwd:resolve('de.local.studiolive-mutes.sdPlugin'),env:{...process.env,HOME:localData,LOCALAPPDATA:localData},windowsHide:true,stdio:'pipe'});children.push(child);return child;
  };
  const action=(event:string,payload:any={})=>host.send(JSON.stringify({event,action:'de.local.studiolive-mutes.channel',context:'button',device:'simdeck',payload:{controller:'Keypad',settings:{channel:1},coordinates:{column:0,row:0},...payload}}));
  const first=launch();await until(()=>received.some(m=>m.event==='getGlobalSettings'),2000);
  action('willAppear');action('propertyInspectorDidAppear');
  action('sendToPlugin',{type:'mixerSettings',operation:'load',requestId:'load'});
  await until(()=>received.some(m=>m.event==='sendToPropertyInspector'&&m.payload.requestId==='load'),2000);
  assert.equal(received.find(m=>m.payload?.requestId==='load').payload.settings.ip,'');
  assert.equal(received.filter(m=>m.event==='setGlobalSettings').length,0);assert.equal(fixture.writes.length,0);
  action('sendToPlugin',{type:'mixerSettings',operation:'save',requestId:'save',ip:'127.0.0.1'});
  await until(()=>received.some(m=>m.event==='sendToPropertyInspector'&&m.payload.requestId==='save'&&m.payload.ok),2000);
  assert.equal(JSON.parse(await readFile(mixerAddressFile(process.platform,localData,{LOCALAPPDATA:localData}),'utf8')).ip,'127.0.0.1');
  assert.equal(received.find(m=>m.event==='setGlobalSettings').context,'de.local.studiolive-mutes');
  const exited=new Promise(resolve=>first.once('exit',resolve));first.kill();await exited;
  const previousConnections=received.filter(m=>m.event==='registerPlugin').length;const previousSubscribe=fixture.writes.filter(b=>b.toString('ascii',6,8)==='JM').length;const checkpoint=received.length;
  launch();await until(()=>received.filter(m=>m.event==='registerPlugin').length>previousConnections,2000);action('willAppear');
  await until(()=>fixture.writes.filter(b=>b.toString('ascii',6,8)==='JM').length>previousSubscribe,2000);
  await until(()=>received.slice(checkpoint).some(m=>m.event==='setImage'&&m.context==='button'&&Buffer.from(String(m.payload.image).split(',')[1],'base64').toString().includes('>OPEN<')),2000);
  assert.equal(fixture.controls.length,0);
});
